"""Two PDFs per job notice: a short drive notice and a detailed, explained job description."""
import json
from io import BytesIO
from xml.sax.saxutils import escape
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

_S = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=_S["Title"], fontName="Helvetica-Bold", fontSize=15, leading=19, spaceAfter=4)
H2 = ParagraphStyle("h2", parent=_S["Heading2"], fontName="Helvetica-Bold", fontSize=12, spaceBefore=10, spaceAfter=4)
B = ParagraphStyle("b", parent=_S["BodyText"], fontName="Helvetica", fontSize=10, leading=14)
SM = ParagraphStyle("sm", parent=B, fontSize=9, leading=12)
CEN = ParagraphStyle("c", parent=B, alignment=1, fontName="Helvetica-Bold")
P = lambda t, s=B: Paragraph(escape(str(t)), s)

def _footer(c, d):
    c.saveState(); c.setFont("Helvetica", 8); c.setFillColor(colors.grey)
    c.drawString(18 * mm, 10 * mm, "Recruitment notice - generated by Recruiter Agent"); c.drawRightString(192 * mm, 10 * mm, f"Page {d.page}"); c.restoreState()

def _doc(story):
    buf = BytesIO(); SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm).build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()

def _meta(jb):
    m = json.loads(jb.get("meta") or "{}"); m["location"] = jb["location"]; m.setdefault("salary_lpa", jb["budget_lpa"]); return m

def _rows(jb, m):
    return [("Name of Company", m["company"]), ("Eligible Course", m["course"]), ("Eligible Passing / Passed out Batch", m["batch"]),
            ("Eligible Branches", m["branches"]), ("Eligibility Criteria", m["criteria"]), ("Candidates Required", "All genders (equal opportunity)"),
            ("Job Offered / Employment Role", jb["title"]), ("Required Skills", ", ".join(json.loads(jb["must"]))), ("Preferred Skills", ", ".join(json.loads(jb["nice"]))),
            ("Duration of Internship / Probation", f"{m['months']} months"),
            ("Stipend during Internship / Probation", f"On joining total pay (fixed pay) INR {m['stipend_lpa']} LPA"),
            ("Salary Offered after Internship / Probation", f"On completion of {m['months']} months INR {m['salary_lpa']} LPA"),
            ("Job / Internship Location", jb["location"]), ("Apply Link", m["apply_link"]), ("Last date to Apply", m["last_date"]), ("Mode of Campus / Internship", m["mode"])]

def notice_pdf(jb):
    m = _meta(jb); no = m["notice_no"]
    data = [[P("Sl.", SM), P("PARTICULARS", SM), P("COMPANY DETAILS", SM)]] + [[P(f"{i:02d}", SM), P(k, SM), P(v, SM)] for i, (k, v) in enumerate(_rows(jb, m), 1)]
    t = Table(data, colWidths=[12 * mm, 62 * mm, 98 * mm], repeatRows=1)
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), .6, colors.black), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eeeeee")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story = [P(f"CAMPUS DRIVE NOTICE (2026) - {no[-2:]} - {m['company']}", H1), P(f"No.: {no}        Date: {m['notice_date']}", B), Spacer(1, 4),
             P(f"{m['company']} is organizing a drive for Internship-cum-Recruitment for the role of {jb['title']} as per the description below:", B), Spacer(1, 6), t, Spacer(1, 8),
             P("Applicants please note: read the job description carefully and apply in accordance with the eligibility criteria.", CEN),
             P("1. Only eligible and unselected applicants can apply.  2. Submit your consent at the apply link before the last date.  "
               "3. Shortlisting is based on skills and experience only; offers and rejections are released after human approval.  "
               "4. Leaving the selection process midway may affect future opportunities.", SM)]
    return _doc(story)

def detail_pdf(jb):
    m = _meta(jb); must = json.loads(jb["must"]); nice = json.loads(jb["nice"]); title = jb["title"]; co = m["company"]
    bl = lambda items: [P("- " + i) for i in items]
    story = [P(f"{title} - {co}", H1), P(f"Detailed job description and hiring guide  |  Notice {m['notice_no']}  |  {m['notice_date']}", SM),
        P("1. About this opportunity", H2),
        P(f"{co} is hiring a {title} for its {jb['location']} team through an internship-cum-recruitment programme. You first join as an intern or probationer for "
          f"{m['months']} months. If your performance is good during this period, you continue as a regular employee at the higher salary listed below."),
        P("2. Who can apply", H2),
        P(f"Course: {m['course']}. Passing batch: {m['batch']}. Eligible branches: {m['branches']}. Academic criteria: {m['criteria']}. "
          "'No active backlogs' means you should not have any failed subject pending at the time of applying. This role is open to candidates of all genders; "
          "selection is based only on skills, experience and interview performance."),
        P("3. What you will do", H2)] + bl(m.get("resp") or ["Work with the team on assigned tasks", "Learn and apply the required skills", "Document and share progress"]) + [
        P("4. Skills explained", H2),
        P(f"Must-have skills: {', '.join(must)}. You should be able to show these in your resume through projects, internships or coursework. "
          f"Preferred skills: {', '.join(nice)}. These are not compulsory but improve your score. At least {jb['min_exp']:g} year(s) of relevant experience "
          "(internships and projects count) is expected."),
        P("How candidates are scored: skills match 60 points, preferred skills 15 points, experience 25 points. Candidates scoring 60 or above are shortlisted.", B),
        P("5. Pay and location explained", H2),
        P(f"Stipend (during the {m['months']}-month internship/probation): INR {m['stipend_lpa']} LPA fixed pay, paid monthly from the day you join. "
          f"Salary after completion: INR {m['salary_lpa']} LPA once the {m['months']} months are completed successfully. LPA means lakhs per annum, i.e. total yearly pay. "
          f"Work location: {jb['location']}. Mode: {m['mode']}."),
        P("6. Selection process, step by step", H2)] + bl([
            "Apply: fill the form at the apply link before the last date and submit your consent.",
            "Profile scan: your skills and experience are scored against the job description. Names and personal details are not used for scoring.",
            "Screening call: a short check of your notice period, salary expectation and location.",
            "Technical interview: questions on the must-have skills of the role.",
            "HR interview: discussion on role expectations, joining and fit.",
            "Offer: the offer letter and every rejection is reviewed and approved by a human recruiter before it is sent."]) + [
        P("7. Important dates", H2), P(f"Last date to apply: {m['last_date']}.  Application link: {m['apply_link']}"),
        P("8. Instructions for applicants", H2)] + bl([
            "Read this description fully and apply only if you meet the eligibility criteria.",
            "Keep your resume, mark sheets and ID proof ready for verification.",
            "Attend scheduled rounds on time; leaving the process midway may affect future opportunities.",
            "Your data is used only for this hiring process and handled under privacy rules."])
    return _doc(story)